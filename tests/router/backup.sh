#!/bin/bash
# tests/router/backup.sh — ШАГ 2: снять бэкап конфигурации роутера и напечатать путь назад.
#
#     R_HOST=192.168.1.1 R_KEY=~/.ssh/id_ed25519 bash tests/router/backup.sh
#
# Отдельным шагом, а не «внутри установки»: путь назад не должен зависеть от нашего же кода
# откатa. Если что-то пойдёт не так на любом следующем шаге — восстановление одной командой,
# и оно работает даже если наш движок сломан целиком.

set -e -u -o pipefail
. "$(cd "$(dirname "$0")" && pwd)/lib.sh"

r_init "backup"
r_backup
r_finish
